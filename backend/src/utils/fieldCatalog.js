/**
 * Returns 4 to 6 top assessment topics for any user based on their field and career goal.
 */
export function getRecommendedTopicsForField(field, careerGoal) {
  const normField = field || "Software Development";
  
  // 1. Check exact or partial match in FIELD_CORE_TOPICS
  let topics = FIELD_CORE_TOPICS[normField];
  if (!topics) {
    const matchKey = Object.keys(FIELD_CORE_TOPICS).find(
      k => k.toLowerCase().includes(normField.toLowerCase()) || normField.toLowerCase().includes(k.toLowerCase())
    );
    if (matchKey) topics = FIELD_CORE_TOPICS[matchKey];
  }

  // 2. Fallback to career goals for this field if specific topics not defined
  if (!topics || topics.length === 0) {
    topics = CAREER_GOALS_BY_FIELD[normField] || [
      `${normField} Core Principles`,
      `${normField} Practical Application`,
      `${normField} Advanced Concepts`,
      `${normField} Industry Best Practices`
    ];
  }

  // 3. If user has a specific careerGoal, prioritize topics that match it
  if (careerGoal) {
    const goalLower = careerGoal.toLowerCase();
    const sorted = [...topics].sort((a, b) => {
      const aMatch = a.toLowerCase().includes(goalLower) || goalLower.includes(a.toLowerCase());
      const bMatch = b.toLowerCase().includes(goalLower) || goalLower.includes(b.toLowerCase());
      if (aMatch && !bMatch) return -1;
      if (!aMatch && bMatch) return 1;
      return 0;
    });
    return sorted.slice(0, 6);
  }

  return topics.slice(0, 6);
}
